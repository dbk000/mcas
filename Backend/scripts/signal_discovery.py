def scan_MR1_bb_reversion(
    bars: list[dict], symbol: str, atr_s: np.ndarray, rsi_s: np.ndarray,
    bb_mid: np.ndarray, bb_upper: np.ndarray, bb_lower: np.ndarray,
    clv_s: np.ndarray, vol_z: np.ndarray,
) -> list[RawSignal]:
    """
    MR1: Bollinger Band Mean Reversion

    Long: Close below lower BB + RSI < 30 + reversal candle (CLV > 0.5)
    Short: Close above upper BB + RSI > 70 + reversal candle (CLV < 0.5)
    Stop: Beyond the extreme + 1 ATR
    Target: Let trail handle (no TP)
    """
    signals = []
    closes = np.array([b["close"] for b in bars])

    for i in range(MIN_BARS_NEEDED, len(bars) - 1):
        bar = bars[i]
        close = closes[i]
        atr = atr_s[i]
        rsi = rsi_s[i]

        if atr <= 0:
            continue

        # Long: close below lower BB, RSI extreme, reversal candle
        if close < bb_lower[i] and rsi < 30 and clv_s[i] > 0.50:
            stop = bar["low"] - 1.0 * atr
            entry = bars[i + 1]["open"]  # next bar open
            if stop <= 0 or entry <= 0:
                continue
            r_val = entry - stop
            stop_pct = r_val / entry
            if r_val > 0 and stop_pct <= MAX_STOP_PCT:
                bar_ts = bar["bar_start_ts"]
                if bar_ts.tzinfo is None:
                    bar_ts = bar_ts.replace(tzinfo=timezone.utc)
                signals.append(RawSignal(
                    strategy="MR1", symbol=symbol, timeframe="1h",
                    direction="long", bar_ts=bar_ts,
                    entry_price=entry, stop_price=stop, r_value=r_val,
                    score=min(1.0, (30 - rsi) / 20),  # deeper RSI = better
                    reason=f"BB lower touch, RSI={rsi:.0f}, CLV={clv_s[i]:.2f}",
                ))

        # Short: close above upper BB, RSI extreme, reversal candle
        if close > bb_upper[i] and rsi > 70 and clv_s[i] < 0.50:
            stop = bar["high"] + 1.0 * atr
            entry = bars[i + 1]["open"]
            if entry < MIN_SHORT_PRICE:
                continue
            r_val = stop - entry
            stop_pct = r_val / entry
            if r_val > 0 and stop_pct <= MAX_STOP_PCT:
                bar_ts = bar["bar_start_ts"]
                if bar_ts.tzinfo is None:
                    bar_ts = bar_ts.replace(tzinfo=timezone.utc)
                signals.append(RawSignal(
                    strategy="MR1", symbol=symbol, timeframe="1h",
                    direction="short", bar_ts=bar_ts,
                    entry_price=entry, stop_price=stop, r_value=r_val,
                    score=min(1.0, (rsi - 70) / 20),
                    reason=f"BB upper touch, RSI={rsi:.0f}, CLV={clv_s[i]:.2f}",
                ))

    return signals


def scan_MR2_rsi_extreme(
    bars: list[dict], symbol: str, atr_s: np.ndarray, rsi_s: np.ndarray,
    ema20: np.ndarray, vol_z: np.ndarray,
) -> list[RawSignal]:
    """
    MR2: RSI Extreme Snapback

    Long: RSI crosses back above 25 after being below 20 (confirmed reversal)
    Short: RSI crosses back below 75 after being above 80
    Additional: Volume declining (exhaustion)
    Stop: Recent swing low/high (5-bar)
    """
    signals = []
    closes = np.array([b["close"] for b in bars])

    for i in range(MIN_BARS_NEEDED, len(bars) - 1):
        bar = bars[i]
        atr = atr_s[i]

        if atr <= 0 or i < 5:
            continue

        # Long: RSI was < 20 within last 3 bars, now > 25
        rsi_now = rsi_s[i]
        rsi_was_extreme = any(rsi_s[j] < 20 for j in range(max(0, i - 3), i))
        vol_declining = vol_z[i] < vol_z[i - 1] if i > 0 else False

        if rsi_was_extreme and rsi_now > 25 and rsi_now < 45 and vol_declining:
            # Stop at 5-bar swing low
            swing_low = min(bars[j]["low"] for j in range(i - 4, i + 1))
            stop = swing_low - 0.5 * atr
            entry = bars[i + 1]["open"]
            if stop <= 0 or entry <= 0:
                continue
            r_val = entry - stop
            stop_pct = r_val / entry
            if r_val > 0 and stop_pct <= MAX_STOP_PCT:
                bar_ts = bar["bar_start_ts"]
                if bar_ts.tzinfo is None:
                    bar_ts = bar_ts.replace(tzinfo=timezone.utc)
                signals.append(RawSignal(
                    strategy="MR2", symbol=symbol, timeframe="1h",
                    direction="long", bar_ts=bar_ts,
                    entry_price=entry, stop_price=stop, r_value=r_val,
                    score=min(1.0, (25 - min(rsi_s[j] for j in range(max(0, i - 3), i))) / 15),
                    reason=f"RSI snapback from {min(rsi_s[j] for j in range(max(0, i-3), i)):.0f}→{rsi_now:.0f}",
                ))

        # Short: RSI was > 80 within last 3 bars, now < 75
        rsi_was_extreme_high = any(rsi_s[j] > 80 for j in range(max(0, i - 3), i))
        if rsi_was_extreme_high and rsi_now < 75 and rsi_now > 55 and vol_declining:
            swing_high = max(bars[j]["high"] for j in range(i - 4, i + 1))
            stop = swing_high + 0.5 * atr
            entry = bars[i + 1]["open"]
            if entry < MIN_SHORT_PRICE:
                continue
            r_val = stop - entry
            stop_pct = r_val / entry
            if r_val > 0 and stop_pct <= MAX_STOP_PCT:
                bar_ts = bar["bar_start_ts"]
                if bar_ts.tzinfo is None:
                    bar_ts = bar_ts.replace(tzinfo=timezone.utc)
                signals.append(RawSignal(
                    strategy="MR2", symbol=symbol, timeframe="1h",
                    direction="short", bar_ts=bar_ts,
                    entry_price=entry, stop_price=stop, r_value=r_val,
                    score=min(1.0, (max(rsi_s[j] for j in range(max(0, i - 3), i)) - 80) / 15),
                    reason=f"RSI snapback from {max(rsi_s[j] for j in range(max(0, i-3), i)):.0f}→{rsi_now:.0f}",
                ))

    return signals


