# ─── Indicator computation (lightweight, from raw arrays) ─────────────────────

def compute_ema(data: np.ndarray, n: int) -> np.ndarray:
    """EMA series."""
    if len(data) < n:
        return np.full(len(data), np.mean(data))
    alpha = 2.0 / (n + 1)
    result = np.zeros(len(data))
    result[n - 1] = np.mean(data[:n])
    for i in range(n, len(data)):
        result[i] = alpha * data[i] + (1 - alpha) * result[i - 1]
    result[:n - 1] = result[n - 1]
    return result


def compute_sma(data: np.ndarray, n: int) -> np.ndarray:
    """SMA series."""
    if len(data) < n:
        return np.full(len(data), np.mean(data))
    result = np.convolve(data, np.ones(n) / n, mode='full')[:len(data)]
    result[:n - 1] = result[n - 1]
    return result


def compute_atr_series(highs: np.ndarray, lows: np.ndarray, closes: np.ndarray, n: int = 14) -> np.ndarray:
    """ATR series."""
    tr = np.zeros(len(closes))
    tr[0] = highs[0] - lows[0]
    for i in range(1, len(closes)):
        tr[i] = max(highs[i] - lows[i], abs(highs[i] - closes[i - 1]), abs(lows[i] - closes[i - 1]))
    atr = np.zeros(len(closes))
    atr[:n] = np.mean(tr[:n])
    for i in range(n, len(closes)):
        atr[i] = np.mean(tr[i - n + 1:i + 1])
    return atr


def compute_rsi_series(closes: np.ndarray, n: int = 14) -> np.ndarray:
    """RSI series (Wilder's smoothed)."""
    if len(closes) < n + 1:
        return np.full(len(closes), 50.0)
    deltas = np.diff(closes)
    gains = np.where(deltas > 0, deltas, 0.0)
    losses = np.where(deltas < 0, -deltas, 0.0)
    avg_gain = np.zeros(len(deltas))
    avg_loss = np.zeros(len(deltas))
    avg_gain[n - 1] = np.mean(gains[:n])
    avg_loss[n - 1] = np.mean(losses[:n])
    for i in range(n, len(deltas)):
        avg_gain[i] = (avg_gain[i - 1] * (n - 1) + gains[i]) / n
        avg_loss[i] = (avg_loss[i - 1] * (n - 1) + losses[i]) / n
    rsi = np.full(len(closes), 50.0)
    for i in range(n, len(closes)):
        if avg_loss[i - 1] == 0:
            rsi[i] = 100.0
        else:
            rs = avg_gain[i - 1] / avg_loss[i - 1]
            rsi[i] = 100.0 - (100.0 / (1.0 + rs))
    return rsi


def compute_bbands(closes: np.ndarray, n: int = 20, k: float = 2.0):
    """Bollinger Bands. Returns (middle, upper, lower) series."""
    mid = compute_sma(closes, n)
    std = np.zeros(len(closes))
    for i in range(n - 1, len(closes)):
        std[i] = np.std(closes[i - n + 1:i + 1])
    std[:n - 1] = std[n - 1]
    upper = mid + k * std
    lower = mid - k * std
    return mid, upper, lower


def compute_volume_z(volumes: np.ndarray, n: int = 20) -> np.ndarray:
    """Volume Z-score series."""
    result = np.zeros(len(volumes))
    for i in range(n, len(volumes)):
        window = volumes[i - n + 1:i + 1]
        mean = np.mean(window)
        std = np.std(window)
        result[i] = (volumes[i] - mean) / std if std > 0 else 0.0
    return result


def compute_clv(highs: np.ndarray, lows: np.ndarray, closes: np.ndarray) -> np.ndarray:
    """Close Location Value series."""
    ranges = highs - lows
    ranges = np.where(ranges == 0, 1.0, ranges)
    return (closes - lows) / ranges


