def scan_ENG1_engulfing_reversal(
    bars: list[dict], symbol: str, atr_s: np.ndarray, rsi_s: np.ndarray,
    bb_upper: np.ndarray, bb_lower: np.ndarray, vol_z: np.ndarray,
) -> list[RawSignal]:
    """
    ENG1: Engulfing Reversal at BBand Extreme

    Signal: Bullish/bearish engulfing candle at Bollinger Band extreme
    Gate: RSI extreme (< 35 long, > 65 short) + volume confirmation
    Stop: Beyond engulfing candle extreme
    """
    signals = []
    closes = np.array([b["close"] for b in bars])
    opens = np.array([b["open"] for b in bars])

    for i in range(MIN_BARS_NEEDED, len(bars) - 1):
        bar = bars[i]
        prev = bars[i - 1]
        atr = atr_s[i]

        if atr <= 0:
            continue

        # Bullish engulfing: current bar closes above prev open, current open below prev close
        bull_engulf = (
            prev["close"] < prev["open"] and  # prev was bearish
            bar["close"] > bar["open"] and     # current is bullish
            bar["close"] > prev["open"] and    # body covers prev
            bar["open"] < prev["close"] and    # opened below prev close
            vol_z[i] > 1.0                     # volume confirmation
        )

        if bull_engulf and closes[i] < bb_lower[i] + atr and rsi_s[i] < 35:
            stop = min(bar["low"], prev["low"]) - 0.5 * atr
            entry = bars[i + 1]["open"]
            if stop <= 0 or entry <= 0:
                continue
            r_val = entry - stop
            stop_pct = r_val / entry
            if r_val > 0 and stop_pct <= MAX_STOP_PCT:
                bar_ts = bar["bar_start_ts"]
                if bar_ts.tzinfo is None:
                    bar_ts = bar_ts.replace(tzinfo=timezone.utc)
                signals.append(RawSignal(
                    strategy="ENG1", symbol=symbol, timeframe="1h",
                    direction="long", bar_ts=bar_ts,
                    entry_price=entry, stop_price=stop, r_value=r_val,
                    score=min(1.0, (35 - rsi_s[i]) / 20 + (vol_z[i] - 1.0) / 4.0),
                    reason=f"Bull engulf at BB lower, RSI={rsi_s[i]:.0f}",
                ))

        # Bearish engulfing
        bear_engulf = (
            prev["close"] > prev["open"] and  # prev was bullish
            bar["close"] < bar["open"] and     # current is bearish
            bar["close"] < prev["open"] and    # body covers prev
            bar["open"] > prev["close"] and    # opened above prev close
            vol_z[i] > 1.0                     # volume confirmation
        )

        if bear_engulf and closes[i] > bb_upper[i] - atr and rsi_s[i] > 65:
            stop = max(bar["high"], prev["high"]) + 0.5 * atr
            entry = bars[i + 1]["open"]
            if entry < MIN_SHORT_PRICE:
                continue
            r_val = stop - entry
            stop_pct = r_val / entry
            if r_val > 0 and stop_pct <= MAX_STOP_PCT:
                bar_ts = bar["bar_start_ts"]
                if bar_ts.tzinfo is None:
                    bar_ts = bar_ts.replace(tzinfo=timezone.utc)
                signals.append(RawSignal(
                    strategy="ENG1", symbol=symbol, timeframe="1h",
                    direction="short", bar_ts=bar_ts,
                    entry_price=entry, stop_price=stop, r_value=r_val,
                    score=min(1.0, (rsi_s[i] - 65) / 20 + (vol_z[i] - 1.0) / 4.0),
                    reason=f"Bear engulf at BB upper, RSI={rsi_s[i]:.0f}",
                ))

    return signals


def scan_CR1_compression_breakout(
    bars: list[dict], symbol: str, atr_s: np.ndarray,
    bb_width_s: np.ndarray, vol_z: np.ndarray, ema20: np.ndarray,
) -> list[RawSignal]:
    """
    CR1: Compression Breakout (volatility expansion)

    Signal: BB width contracts to < 50th percentile of 100-bar lookback,
    then price breaks beyond 10-bar high/low with volume > 2x average.
    Stop: Opposite side of compression range.

    Unlike S1's squeeze (BB inside KC), this uses relative BB width contraction
    and requires volume confirmation on the breakout bar.
    """
    signals = []
    closes = np.array([b["close"] for b in bars])
    highs = np.array([b["high"] for b in bars])
    lows = np.array([b["low"] for b in bars])

    for i in range(MIN_BARS_NEEDED, len(bars) - 1):
        bar = bars[i]
        atr = atr_s[i]

        if atr <= 0 or i < 20:
            continue

        # Check BB width compression: current < 50th percentile of last 100 bars
        lookback = min(100, i)
        bb_hist = bb_width_s[i - lookback:i]
        if len(bb_hist) < 20:
            continue
        pct_50 = np.percentile(bb_hist, 50)

        if bb_width_s[i] >= pct_50:
            continue

        # Must have been compressed for at least 3 bars (not a blip)
        compressed_bars = sum(1 for j in range(max(0, i - 5), i + 1) if bb_width_s[j] < pct_50)
        if compressed_bars < 3:
            continue

        # Volume surge on breakout bar
        if vol_z[i] < 2.0:
            continue

        # 10-bar range for breakout detection
        range_high = float(np.max(highs[i - 10:i]))
        range_low = float(np.min(lows[i - 10:i]))

        # Long breakout: close above 10-bar high
        if closes[i] > range_high and closes[i] > ema20[i]:
            stop = range_low - 0.5 * atr
            entry = bars[i + 1]["open"]
            if stop <= 0 or entry <= 0:
                continue
            r_val = entry - stop
            stop_pct = r_val / entry
            if r_val > 0 and stop_pct <= MAX_STOP_PCT:
                bar_ts = bar["bar_start_ts"]
                if bar_ts.tzinfo is None:
                    bar_ts = bar_ts.replace(tzinfo=timezone.utc)
                signals.append(RawSignal(
                    strategy="CR1", symbol=symbol, timeframe="1h",
                    direction="long", bar_ts=bar_ts,
                    entry_price=entry, stop_price=stop, r_value=r_val,
                    score=min(1.0, vol_z[i] / 4.0),
                    reason=f"Compression breakout up, volZ={vol_z[i]:.1f}, BBw_pct={bb_width_s[i]/pct_50:.2f}",
                ))

        # Short breakout: close below 10-bar low
        if closes[i] < range_low and closes[i] < ema20[i]:
            stop = range_high + 0.5 * atr
            entry = bars[i + 1]["open"]
            if entry < MIN_SHORT_PRICE:
                continue
            r_val = stop - entry
            stop_pct = r_val / entry
            if r_val > 0 and stop_pct <= MAX_STOP_PCT:
                bar_ts = bar["bar_start_ts"]
                if bar_ts.tzinfo is None:
                    bar_ts = bar_ts.replace(tzinfo=timezone.utc)
                signals.append(RawSignal(
                    strategy="CR1", symbol=symbol, timeframe="1h",
                    direction="short", bar_ts=bar_ts,
                    entry_price=entry, stop_price=stop, r_value=r_val,
                    score=min(1.0, vol_z[i] / 4.0),
                    reason=f"Compression breakout down, volZ={vol_z[i]:.1f}",
                ))

    return signals


def scan_DV1_divergence_reversal(
    bars: list[dict], symbol: str, atr_s: np.ndarray, rsi_s: np.ndarray,
    clv_s: np.ndarray, vol_z: np.ndarray,
) -> list[RawSignal]:
    """
    DV1: RSI Divergence Reversal

    Bullish: Price makes lower low (10-bar) but RSI makes higher low → reversal
    Bearish: Price makes higher high (10-bar) but RSI makes lower high → reversal
    Gate: Volume declining on second leg (exhaustion)
    """
    signals = []
    closes = np.array([b["close"] for b in bars])
    lows = np.array([b["low"] for b in bars])
    highs = np.array([b["high"] for b in bars])

    for i in range(MIN_BARS_NEEDED, len(bars) - 1):
        bar = bars[i]
        atr = atr_s[i]

        if atr <= 0 or i < 20:
            continue

        # Find prior swing low/high (10-20 bars back)
        lookback_start = max(0, i - 20)
        lookback_end = max(0, i - 5)  # at least 5 bars ago

        if lookback_end <= lookback_start:
            continue

        # Bullish divergence: price lower low, RSI higher low
        prior_low_idx = lookback_start + int(np.argmin(lows[lookback_start:lookback_end]))
        current_is_low = lows[i] <= float(np.min(lows[i - 3:i + 1]))  # local low

        if current_is_low and lows[i] < lows[prior_low_idx] and rsi_s[i] > rsi_s[prior_low_idx]:
            # Divergence confirmed — RSI higher while price lower
            # Gate: reversal candle (CLV > 0.5) and RSI < 40
            if clv_s[i] > 0.50 and rsi_s[i] < 40:
                stop = lows[i] - 0.75 * atr
                entry = bars[i + 1]["open"]
                if stop <= 0 or entry <= 0:
                    continue
                r_val = entry - stop
                stop_pct = r_val / entry
                if r_val > 0 and stop_pct <= MAX_STOP_PCT:
                    div_strength = (rsi_s[i] - rsi_s[prior_low_idx]) / 20.0  # bigger RSI diff = stronger
                    bar_ts = bar["bar_start_ts"]
                    if bar_ts.tzinfo is None:
                        bar_ts = bar_ts.replace(tzinfo=timezone.utc)
                    signals.append(RawSignal(
                        strategy="DV1", symbol=symbol, timeframe="1h",
                        direction="long", bar_ts=bar_ts,
                        entry_price=entry, stop_price=stop, r_value=r_val,
                        score=min(1.0, div_strength),
                        reason=f"Bull divergence RSI {rsi_s[prior_low_idx]:.0f}→{rsi_s[i]:.0f} while price lower",
                    ))

        # Bearish divergence: price higher high, RSI lower high
        prior_high_idx = lookback_start + int(np.argmax(highs[lookback_start:lookback_end]))
        current_is_high = highs[i] >= float(np.max(highs[i - 3:i + 1]))

        if current_is_high and highs[i] > highs[prior_high_idx] and rsi_s[i] < rsi_s[prior_high_idx]:
            if clv_s[i] < 0.50 and rsi_s[i] > 60:
                stop = highs[i] + 0.75 * atr
                entry = bars[i + 1]["open"]
                if entry < MIN_SHORT_PRICE:
                    continue
                r_val = stop - entry
                stop_pct = r_val / entry
                if r_val > 0 and stop_pct <= MAX_STOP_PCT:
                    div_strength = (rsi_s[prior_high_idx] - rsi_s[i]) / 20.0
                    bar_ts = bar["bar_start_ts"]
                    if bar_ts.tzinfo is None:
                        bar_ts = bar_ts.replace(tzinfo=timezone.utc)
                    signals.append(RawSignal(
                        strategy="DV1", symbol=symbol, timeframe="1h",
                        direction="short", bar_ts=bar_ts,
                        entry_price=entry, stop_price=stop, r_value=r_val,
                        score=min(1.0, div_strength),
                        reason=f"Bear divergence RSI {rsi_s[prior_high_idx]:.0f}→{rsi_s[i]:.0f} while price higher",
                    ))

    return signals


# ─── Trade simulation ─────────────────────────────────────────────────────────

def signal_to_trade(
    signal: RawSignal,
    all_bars: list[dict],
    signal_bar_idx: int,
    time_stop_bars: int = 24,
) -> Optional[SimTrade]:
    """Convert a RawSignal to a SimTrade with proper entry fill and exit bars."""
    entry_bar_idx = signal_bar_idx + 1
    if entry_bar_idx >= len(all_bars):
        return None

    entry_bar = all_bars[entry_bar_idx]
    actual_entry = entry_bar["open"]

    # Apply entry slippage
    if signal.direction == "long":
        entry_with_slip = actual_entry * (1 + SLIPPAGE_ENTRY_BPS / 10000)
    else:
        entry_with_slip = actual_entry * (1 - SLIPPAGE_ENTRY_BPS / 10000)

    # Recalculate R with actual fill
    if signal.direction == "long":
        actual_r = entry_with_slip - signal.stop_price
    else:
        actual_r = signal.stop_price - entry_with_slip

    if actual_r <= 0:
        return None

    # Fee gate
    fee_per_unit = 2 * entry_with_slip * FEE_TAKER_BPS / 10000
    if fee_per_unit > 0.3 * actual_r:
        return None

    # Collect exit bars
    max_bar = min(entry_bar_idx + MAX_BARS_FORWARD, len(all_bars) - 1)
    exit_bars = all_bars[entry_bar_idx + 1:max_bar + 1]

    position_size = POSITION_SIZE_USD / entry_with_slip

    bar_ts = entry_bar["bar_start_ts"]
    if bar_ts.tzinfo is None:
        bar_ts = bar_ts.replace(tzinfo=timezone.utc)

    return SimTrade(
        strategy=signal.strategy,
        direction=signal.direction,
        entry_price=entry_with_slip,
        stop_price=signal.stop_price,
        r_value=actual_r,
        time_stop_bars=time_stop_bars,
        bars=exit_bars,
        created_ts=bar_ts,
        symbol=signal.symbol,
        position_size=position_size,
        score=signal.score,
    )


def run_exit(trade: SimTrade, config: ExitConfig) -> tuple[str, float, int]:
    """Run exit simulation on a trade."""
    hwm = None
    half_r_touched = False
    bars_held = 0

    for bar in trade.bars:
        bars_held += 1
        exit_result, new_hwm, new_half_r = check_exit_simple(
            side=trade.direction,
            bar=bar,
            entry_price=trade.entry_price,
            stop_price=trade.stop_price,
            tp1_price=None,  # no TPs — let trail handle
            tp2_price=None,
            r_value=trade.r_value,
            bars_held=bars_held,
            max_bars=trade.time_stop_bars,
            high_water_mark=hwm,
            half_r_touched=half_r_touched,
            config=config,
        )
        hwm = new_hwm
        half_r_touched = new_half_r
        if exit_result:
            reason, price = exit_result
            return reason, price, bars_held

    if trade.bars:
        return "TIME_STOP", trade.bars[-1]["close"], bars_held
    return "TIME_STOP", trade.entry_price, 0


def compute_pnl(trade: SimTrade, exit_reason: str, exit_price: float) -> tuple[float, float]:
    """Compute PnL and R-multiple."""
    if exit_reason != "STOP_LOSS":
        if trade.direction == "long":
            exit_with_slip = exit_price * (1 - SLIPPAGE_EXIT_BPS / 10000)
        else:
            exit_with_slip = exit_price * (1 + SLIPPAGE_EXIT_BPS / 10000)
    else:
        exit_with_slip = exit_price

    if trade.direction == "long":
        pnl_gross = (exit_with_slip - trade.entry_price) * trade.position_size
    else:
        pnl_gross = (trade.entry_price - exit_with_slip) * trade.position_size

    fee_bps = FEE_TAKER_BPS
    entry_fee = trade.entry_price * trade.position_size * (fee_bps / 10000)
    exit_fee = exit_with_slip * trade.position_size * (fee_bps / 10000)
    pnl_net = pnl_gross - entry_fee - exit_fee

    risk_per_unit = trade.r_value * trade.position_size
    r_multiple = pnl_net / risk_per_unit if risk_per_unit > 0 else 0

    return pnl_net, r_multiple


# ─── Metrics ──────────────────────────────────────────────────────────────────

def calc_metrics(results: list[dict]) -> dict:
    """Compute aggregate metrics."""
    if not results:
        return {"n": 0, "wins": 0, "wr": 0, "pf": 0, "pnl": 0, "avg_r": 0,
                "ff_rate": 0, "exits": {}}

    pnls = [r["pnl"] for r in results]
    rs = [r["r_mult"] for r in results]
    exits = defaultdict(int)
    for r in results:
        exits[r["exit_reason"]] += 1

    n = len(pnls)
    wins = sum(1 for p in pnls if p > 0)
    gp = sum(p for p in pnls if p > 0)
    gl = abs(sum(p for p in pnls if p <= 0))
    ff = exits.get("FAIL_FAST", 0)

    return {
        "n": n,
        "wins": wins,
        "wr": wins / n if n > 0 else 0,
        "pf": gp / gl if gl > 0 else (99.99 if gp > 0 else 0),
        "pnl": sum(pnls),
        "avg_r": sum(rs) / n if n > 0 else 0,
        "ff_rate": ff / n if n > 0 else 0,
        "exits": dict(exits),
    }


# ─── Data loading ─────────────────────────────────────────────────────────────

def load_all_1h_ohlcv(database_url: str, days: int) -> dict[str, list[dict]]:
    """Load all 1h OHLCV data for all symbols."""
    start_ts = datetime.now(timezone.utc) - timedelta(days=days)
    end_ts = datetime.now(timezone.utc)

    with psycopg.connect(database_url) as conn:
        with conn.cursor() as cur:
            # Get all symbols that have 1h data
            cur.execute("""
                SELECT DISTINCT symbol FROM ohlcv
                WHERE timeframe = '1h'
                  AND bar_start_ts >= %s AND bar_start_ts < %s
                  AND is_final = TRUE
            """, (start_ts, end_ts))
            symbols = [row[0] for row in cur.fetchall()]
            logger.info("Found %d symbols with 1h data", len(symbols))

            cache = {}
            for idx, symbol in enumerate(symbols):
                cur.execute("""
                    SELECT DISTINCT ON (bar_start_ts)
                           bar_start_ts, open, high, low, close, volume
                    FROM ohlcv
                    WHERE symbol = %s AND timeframe = '1h'
                      AND bar_start_ts >= %s AND bar_start_ts < %s
                      AND is_final = TRUE
                    ORDER BY bar_start_ts,
                             CASE source
                                 WHEN 'ws' THEN 0
                                 WHEN 'binance' THEN 1
                                 ELSE 2
                             END;
                """, (symbol, start_ts, end_ts))

                rows = cur.fetchall()
                if len(rows) < MIN_BARS_NEEDED:
                    continue

                bars = [{
                    "bar_start_ts": row[0],
                    "open": float(row[1]),
                    "high": float(row[2]),
                    "low": float(row[3]),
                    "close": float(row[4]),
                    "volume": float(row[5]),
                } for row in rows]
                cache[symbol] = bars

                if (idx + 1) % 50 == 0:
                    logger.info("OHLCV loaded: %d/%d symbols (%d with sufficient bars)",
                               idx + 1, len(symbols), len(cache))

    total_bars = sum(len(v) for v in cache.values())
    logger.info("OHLCV loaded: %d symbols with %d+ bars, %d total bars",
               len(cache), MIN_BARS_NEEDED, total_bars)
    return cache


# ─── Main scan + simulate ────────────────────────────────────────────────────

def scan_symbol(symbol: str, bars: list[dict]) -> list[RawSignal]:
    """Run all signal strategies on one symbol's bars."""
    closes = np.array([b["close"] for b in bars])
    highs = np.array([b["high"] for b in bars])
    lows = np.array([b["low"] for b in bars])
    volumes = np.array([b["volume"] for b in bars])

    # Compute indicators
    atr_s = compute_atr_series(highs, lows, closes, 14)
    rsi_s = compute_rsi_series(closes, 14)
    ema20 = compute_ema(closes, 20)
    bb_mid, bb_upper, bb_lower = compute_bbands(closes, 20, 2.0)
    vol_z = compute_volume_z(volumes, 20)
    clv_s = compute_clv(highs, lows, closes)

    # BB width series
    bb_width_s = np.zeros(len(closes))
    for i in range(len(closes)):
        if bb_mid[i] > 0:
            bb_width_s[i] = (bb_upper[i] - bb_lower[i]) / bb_mid[i]

    signals = []

    # Run all strategies
    signals.extend(scan_MR1_bb_reversion(
        bars, symbol, atr_s, rsi_s, bb_mid, bb_upper, bb_lower, clv_s, vol_z))

    signals.extend(scan_MR2_rsi_extreme(
        bars, symbol, atr_s, rsi_s, ema20, vol_z))

    signals.extend(scan_VR1_volume_climax(
        bars, symbol, atr_s, vol_z, clv_s, rsi_s))

    signals.extend(scan_ENG1_engulfing_reversal(
        bars, symbol, atr_s, rsi_s, bb_upper, bb_lower, vol_z))

    signals.extend(scan_CR1_compression_breakout(
        bars, symbol, atr_s, bb_width_s, vol_z, ema20))

    signals.extend(scan_DV1_divergence_reversal(
        bars, symbol, atr_s, rsi_s, clv_s, vol_z))

    return signals


def simulate_signals(
    all_signals: list[RawSignal],
    ohlcv_cache: dict[str, list[dict]],
    config: ExitConfig,
    time_stop_bars: int = 24,
) -> list[dict]:
    """Simulate all signals and return results."""
    results = []

    # Build bar timestamp index per symbol for fast lookup
    bar_idx_cache: dict[str, dict[datetime, int]] = {}
    for symbol, bars in ohlcv_cache.items():
        idx_map = {}
        for i, bar in enumerate(bars):
            ts = bar["bar_start_ts"]
            if ts.tzinfo is None:
                ts = ts.replace(tzinfo=timezone.utc)
            idx_map[ts] = i
        bar_idx_cache[symbol] = idx_map

    for signal in all_signals:
        bars = ohlcv_cache.get(signal.symbol, [])
        if not bars:
            continue

        idx_map = bar_idx_cache.get(signal.symbol, {})
        bar_ts = signal.bar_ts
        if bar_ts.tzinfo is None:
            bar_ts = bar_ts.replace(tzinfo=timezone.utc)
        signal_bar_idx = idx_map.get(bar_ts)
        if signal_bar_idx is None:
            continue

        trade = signal_to_trade(signal, bars, signal_bar_idx, time_stop_bars)
        if trade is None:
            continue

        exit_reason, exit_price, bars_held = run_exit(trade, config)
        pnl, r_mult = compute_pnl(trade, exit_reason, exit_price)

        results.append({
            "strategy": signal.strategy,
            "symbol": signal.symbol,
            "direction": signal.direction,
            "pnl": pnl,
            "r_mult": r_mult,
            "exit_reason": exit_reason,
            "bars_held": bars_held,
            "created_ts": trade.created_ts,
            "score": signal.score,
        })

    return results


