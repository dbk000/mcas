    parser.add_argument("--days", type=int, default=30, help="Days of OHLCV to load")
    args = parser.parse_args()

    database_url = os.environ.get("DATABASE_URL")
    if not database_url:
        logger.error("DATABASE_URL not set")
        sys.exit(1)

    t0 = time.time()

    # ── Load OHLCV ────────────────────────────────────────────────────────
    logger.info("Loading %d days of 1h OHLCV data...", args.days)
    ohlcv_cache = load_all_1h_ohlcv(database_url, args.days)
    if not ohlcv_cache:
        logger.error("No OHLCV data found")
        sys.exit(1)

    # ── Scan for signals ──────────────────────────────────────────────────
    logger.info("Scanning %d symbols for signal hypotheses...", len(ohlcv_cache))
    all_signals = []
    for idx, (symbol, bars) in enumerate(ohlcv_cache.items()):
        signals = scan_symbol(symbol, bars)
        all_signals.extend(signals)
        if (idx + 1) % 50 == 0:
            logger.info("Scanned %d/%d symbols, %d signals so far",
                       idx + 1, len(ohlcv_cache), len(all_signals))

    logger.info("Total raw signals: %d", len(all_signals))

    # Signal count by strategy
    by_strat = defaultdict(int)
    for s in all_signals:
        by_strat[s.strategy] += 1
    for strat, count in sorted(by_strat.items()):
        logger.info("  %s: %d signals", strat, count)

    # ── Exit config sweep ─────────────────────────────────────────────────
    # Test multiple exit configs to find what works with these signal types
    configs = [
        ("Tight_trail",   ExitConfig(trail_breakeven_r=0, trail_activation_r=0.75, trail_distance_r=0.50)),
        ("Medium_trail",  ExitConfig(trail_breakeven_r=0, trail_activation_r=1.0,  trail_distance_r=0.75)),
        ("Wide_trail",    ExitConfig(trail_breakeven_r=0, trail_activation_r=1.5,  trail_distance_r=1.0)),
        ("BE_tight",      ExitConfig(trail_breakeven_r=0.5, trail_activation_r=1.0, trail_distance_r=0.50)),
        ("BE_wide",       ExitConfig(trail_breakeven_r=0.75, trail_activation_r=1.5, trail_distance_r=0.75)),
    ]

    # Time stop variants — mean reversion should resolve faster
    time_stops = [12, 24, 48]

    print("\n" + "=" * 100)
    print("SIGNAL DISCOVERY — NEW SIGNAL TYPE RESEARCH")
    print(f"Data: {args.days} days, {len(ohlcv_cache)} symbols, 1h timeframe")
    print(f"Train: < {TRAIN_CUTOFF.strftime('%Y-%m-%d')} | Val: >= {TRAIN_CUTOFF.strftime('%Y-%m-%d')}")
    print(f"Total raw signals: {len(all_signals)}")
    print("=" * 100)

    # ── Run with default config first for overview ────────────────────────
    default_config = ExitConfig(trail_breakeven_r=0, trail_activation_r=1.0, trail_distance_r=0.75)
    default_time_stop = 24

    logger.info("Simulating %d signals with default config (TS=%d)...", len(all_signals), default_time_stop)
    all_results = simulate_signals(all_signals, ohlcv_cache, default_config, default_time_stop)

    train = [r for r in all_results if r["created_ts"] < TRAIN_CUTOFF]
    val = [r for r in all_results if r["created_ts"] >= TRAIN_CUTOFF]

    logger.info("Simulated: %d trades (%d train, %d val)", len(all_results), len(train), len(val))

    print_strategy_table(f"TRAINING (< {TRAIN_CUTOFF.strftime('%b %d')}): default config, TS={default_time_stop}", train)
    print_strategy_table(f"VALIDATION (>= {TRAIN_CUTOFF.strftime('%b %d')}): default config, TS={default_time_stop}", val)
    print_strategy_table(f"FULL DATASET: default config, TS={default_time_stop}", all_results)
    print_direction_table(all_results)

    # ── Exit config sweep per strategy ────────────────────────────────────
    print(f"\n{'EXIT CONFIG SWEEP (per strategy)':^100}")
    print("=" * 100)
    print(f"{'Strategy':>10} {'Config':>14} {'TS':>3} {'TrnN':>5} {'TrnWR':>6} {'TrnPF':>7} "
          f"{'TrnPnL':>10} {'ValN':>5} {'ValWR':>6} {'ValPF':>7} {'ValPnL':>10} {'OvFit':>6}")
