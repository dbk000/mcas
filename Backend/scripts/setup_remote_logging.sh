#!/usr/bin/env bash
# =============================================================================
# MCAS Remote Security Log Forwarding Setup
# =============================================================================
#
# Forwards auth/sudo/SSH logs off-site via rsyslog over TLS so they
# survive even if an attacker wipes local logs.
#
# Supports two modes:
#   1. SolarWinds Observability (TLS + token auth on port 6514)
#   2. Plain TCP/UDP (e.g. self-hosted syslog)
#
# Usage:
#   sudo ./setup_remote_logging.sh <host:port> [--token TOKEN]
#   sudo ./setup_remote_logging.sh <host:port> --udp
#
# Examples:
#   sudo ./setup_remote_logging.sh syslog.collector.eu-01.cloud.solarwinds.com:6514 --token YOUR_TOKEN
#   sudo ./setup_remote_logging.sh logs5.papertrailapp.com:12345
#
# Idempotent — safe to re-run with a new endpoint.
# =============================================================================

set -euo pipefail

CONF_FILE="/etc/rsyslog.d/50-remote-security.conf"

# --- Arg parsing ---
if [[ $# -lt 1 ]]; then
    echo "Usage: sudo $0 <host:port> [--token TOKEN] [--udp]"
    echo ""
    echo "  host:port     Log destination"
    echo "  --token TOKEN SolarWinds API token (required for port 6514/TLS)"
    echo "  --udp         Use UDP instead of TCP (not for TLS)"
    exit 1
fi

ENDPOINT="$1"
shift
TOKEN=""
PROTOCOL="tcp"

while [[ $# -gt 0 ]]; do
    case "$1" in
        --token) TOKEN="$2"; shift 2 ;;
        --udp)   PROTOCOL="udp"; shift ;;
        *)       echo "Unknown arg: $1"; exit 1 ;;
    esac
done

# Validate endpoint format
if [[ ! "$ENDPOINT" =~ ^[a-zA-Z0-9._-]+:[0-9]+$ ]]; then
    echo "ERROR: Invalid endpoint format. Expected host:port"
    exit 1
fi

HOST="${ENDPOINT%%:*}"
PORT="${ENDPOINT##*:}"

# Must run as root
if [[ $EUID -ne 0 ]]; then
    echo "ERROR: This script must be run as root (sudo)."
    exit 1
fi

# Check rsyslog is installed
if ! command -v rsyslogd &> /dev/null; then
    echo "ERROR: rsyslog not found. Install with: apt install rsyslog"
    exit 1
fi

# Detect TLS mode (port 6514 or token provided)
USE_TLS=false
if [[ "$PORT" == "6514" ]] || [[ -n "$TOKEN" ]]; then
    USE_TLS=true
fi

echo "=== MCAS Remote Security Log Setup ==="
echo "Endpoint:  $ENDPOINT"
echo "TLS:       $USE_TLS"
if [[ -n "$TOKEN" ]]; then
    echo "Token:     ${TOKEN:0:8}...${TOKEN: -4} (redacted)"
fi
echo "Config:    $CONF_FILE"
echo ""

# --- Install TLS support if needed ---
if [[ "$USE_TLS" == "true" ]]; then
    if ! dpkg -l rsyslog-gnutls &>/dev/null 2>&1; then
        echo "Installing rsyslog-gnutls for TLS support..."
        apt-get update -qq && apt-get install -y -qq rsyslog-gnutls
        echo "rsyslog-gnutls installed."
    else
        echo "rsyslog-gnutls already installed."
    fi
fi

# --- Write rsyslog config ---
if [[ "$USE_TLS" == "true" ]]; then
    # TLS mode (SolarWinds Observability / any RFC 5425 endpoint)
    cat > "$CONF_FILE" << RSYSEOF
# =============================================================================
# MCAS Security Log Forwarding (TLS + Token Auth)
# Generated by setup_remote_logging.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
# =============================================================================
#
# Forwards auth/sudo/SSH logs to SolarWinds Observability over TLS.
# Token authenticates this host. Logs are encrypted in transit.
#
# Destination: ${ENDPOINT}
# =============================================================================

# --- TLS driver setup ---
\$DefaultNetstreamDriverCAFile /etc/ssl/certs/ca-certificates.crt
\$DefaultNetstreamDriver gtls

# --- Action template with SolarWinds token in RFC 5424 structured data ---
template(name="SolarWindsMCAS" type="string"
    string="<%PRI%>1 %TIMESTAMP:::date-rfc3339% %HOSTNAME% %APP-NAME% %PROCID% %MSGID% [${TOKEN}@41058] %msg%\n"
)

# --- Forwarding rules ---
# All auth/authpriv (SSH, sudo, PAM, su)
auth,authpriv.* action(
    type="omfwd"
    target="${HOST}"
    port="${PORT}"
    protocol="tcp"
    StreamDriver="gtls"
    StreamDriverMode="1"
    StreamDriverAuthMode="x509/name"
    StreamDriverPermittedPeers="${HOST}"
    template="SolarWindsMCAS"
    queue.type="LinkedList"
    queue.size="10000"
    queue.filename="mcas_fwd_auth"
    queue.saveonshutdown="on"
    action.resumeRetryCount="-1"
)

# Kernel warnings (firewall drops, OOM kills)
kern.warning action(
    type="omfwd"
    target="${HOST}"
    port="${PORT}"
    protocol="tcp"
    StreamDriver="gtls"
    StreamDriverMode="1"
    StreamDriverAuthMode="x509/name"
    StreamDriverPermittedPeers="${HOST}"
    template="SolarWindsMCAS"
    queue.type="LinkedList"
    queue.size="1000"
    queue.filename="mcas_fwd_kern"
    queue.saveonshutdown="on"
    action.resumeRetryCount="-1"
)

# MCAS-specific tagged events
# Usage: logger -t mcas-security "your message here"
:syslogtag, startswith, "mcas-security" action(
    type="omfwd"
    target="${HOST}"
    port="${PORT}"
    protocol="tcp"
    StreamDriver="gtls"
    StreamDriverMode="1"
    StreamDriverAuthMode="x509/name"
    StreamDriverPermittedPeers="${HOST}"
    template="SolarWindsMCAS"
    queue.type="LinkedList"
    queue.size="1000"
    queue.filename="mcas_fwd_custom"
    queue.saveonshutdown="on"
    action.resumeRetryCount="-1"
)
RSYSEOF

else
    # Plain TCP/UDP mode
    if [[ "$PROTOCOL" == "tcp" ]]; then
        PREFIX="@@"
    else
        PREFIX="@"
    fi

    cat > "$CONF_FILE" << RSYSEOF
# =============================================================================
# MCAS Security Log Forwarding (Plain ${PROTOCOL^^})
# Generated by setup_remote_logging.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
# =============================================================================

auth,authpriv.* ${PREFIX}${ENDPOINT}
kern.warning ${PREFIX}${ENDPOINT}
:syslogtag, startswith, "mcas-security" ${PREFIX}${ENDPOINT}
RSYSEOF
fi

echo "Config written to $CONF_FILE"

# --- Validate rsyslog config ---
echo "Validating rsyslog configuration..."
VALIDATION_OUTPUT=$(rsyslogd -N1 2>&1 || true)
if echo "$VALIDATION_OUTPUT" | grep -qi "error"; then
    echo "ERROR: rsyslog config validation failed:"
    echo "$VALIDATION_OUTPUT"
    echo ""
    echo "Rolling back..."
    rm -f "$CONF_FILE"
    exit 1
fi
echo "Config valid."

# --- Restart rsyslog ---
echo "Restarting rsyslog..."
systemctl restart rsyslog
echo "rsyslog restarted."

# --- Send test message ---
logger -p auth.info -t mcas-security "Remote logging connection test — MCAS VPS $(hostname) at $(date -u +%Y-%m-%dT%H:%M:%SZ)"
echo ""
echo "=== Setup complete ==="
echo ""
echo "Test message sent. Check your SolarWinds dashboard for:"
echo "  'Remote logging connection test — MCAS VPS ...'"
echo ""
echo "What's being forwarded:"
echo "  - All SSH login attempts (success + failure)"
echo "  - All sudo commands"
echo "  - PAM authentication events"
echo "  - Kernel warnings (firewall drops, OOM)"
echo "  - Anything tagged 'mcas-security'"
echo ""
echo "To send custom MCAS security events from scripts:"
echo "  logger -t mcas-security \"your message here\""
