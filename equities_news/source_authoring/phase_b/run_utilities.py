def main() -> int:
    agent = SectorAgent("utilities")
    agent.preflight()
    rows = agent.read_sector_sheet()
    print(f"[utilities] loaded {len(rows)} rows from bible")

    # Sector YAML.
    agent.author_sector_yaml(SECTOR_ENTRIES)
    print(f"[utilities] authored {len(SECTOR_ENTRIES)} sector entries -> sectors/utilities.yaml")

    # Sub-industry YAMLs.
    paths = agent.author_sub_industry_yamls(SUB_INDUSTRY_ENTRIES)
    for p in paths:
        print(f"[utilities] authored {p.name}")

    # Per-ticker overlay fill.
    missing: list[str] = []
    for row in rows:
        data = OVERLAYS.get(row.ticker)
        if data is None:
            # Default: null everything, default transcript, no sub_industry override.
            agent.fill_overlay(
                row,
                ir_url=None,
                press_release_feed_url=None,
                official_x_handle=None,
                official_linkedin_url=None,
                earnings_transcript_provider="seekingalpha",
                local_regulatory_filings_url=None,
                sub_industry_override=None,
                confidence=0.5,
                authoring_notes={"reason": "ticker not in curated utilities overlay map"},
            )
            missing.append(row.ticker)
            continue
        agent.fill_overlay(
            row,
            ir_url=data.get("ir"),
            press_release_feed_url=data.get("press"),
            official_x_handle=data.get("x"),
            official_linkedin_url=data.get("li"),
            earnings_transcript_provider=data.get("tx", "seekingalpha"),
            local_regulatory_filings_url=data.get("fil"),
            sub_industry_override=data.get("si"),
            confidence=float(data.get("c", 0.7)),
        )

    print(f"[utilities] overlay filled for {len(rows)} rows ({len(missing)} uncurated)")
    if missing:
        print(f"[utilities] uncurated tickers: {missing}")

    # Self-verify.
    issues = agent.self_verify()
    if issues:
        print(f"[utilities] SELF-VERIFY ISSUES:")
        for i in issues:
            print(f"  - {i}")
        return 1
    print(f"[utilities] self-verify: 0 issues")

    # Emit enriched sheet.
    out = agent.emit_enriched_sheet()
    print(f"[utilities] enriched sheet written -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
