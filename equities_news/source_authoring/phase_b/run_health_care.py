def _finalise_overlays() -> dict[str, dict]:
    """Expand all pattern-based biotech overlays + merge explicit overrides into OVERLAYS."""
    out = dict(OVERLAYS)
    for t, (slug, li_slug) in {**_PATTERN_BIOTECH, **_PATTERN_BIOTECH_2}.items():
        if t in out:
            continue  # explicit wins
        out[t] = {
            "ir": f"https://investors.{slug}.com",
            "press": f"https://investors.{slug}.com/news-releases",
            "x": None,
            "li": f"https://www.linkedin.com/company/{li_slug}" if li_slug else None,
            "tx": "seekingalpha",
            "fil": f"https://investors.{slug}.com/sec-filings",
            "si": BIOTECH_CLIN,
            "c": 0.55,
        }
    for t, rec in _EXPLICIT_EXTRA.items():
        out[t] = rec  # explicit extras always win
    for t, rec in _EXPLICIT_GAP_FILL.items():
        out[t] = rec  # final gap-fill always wins
    return out


def main() -> int:
    agent = SectorAgent("health_care")
    agent.preflight()
    rows = agent.read_sector_sheet()
    print(f"[hc] loaded {len(rows)} rows")
    agent.author_sector_yaml(SECTOR_ENTRIES)
    print(f"[hc] authored {len(SECTOR_ENTRIES)} sector entries")
    paths = agent.author_sub_industry_yamls(SUB_INDUSTRY_ENTRIES)
    for p in paths:
        print(f"[hc] authored {p.name}")

    merged = _finalise_overlays()
    print(f"[hc] overlay dict size: {len(merged)} tickers")

    uncurated = []
    for row in rows:
        # Country-aware override first (MRK/DE, SHL/AU collisions)
        data = BY_COUNTRY.get((row.ticker, row.country)) or merged.get(row.ticker)
        if data is None or not data:
            agent.fill_overlay(
                row, ir_url=None, press_release_feed_url=None, official_x_handle=None,
                official_linkedin_url=None, earnings_transcript_provider="seekingalpha",
                local_regulatory_filings_url=None, sub_industry_override=None,
                confidence=0.45, authoring_notes={"reason": "not curated"},
            )
            uncurated.append(row.ticker)
            continue
        # Interpret IR=None as "looked and found none" — still null overlay.
        if data.get("ir") is None and data.get("press") is None:
            agent.fill_overlay(
                row, ir_url=None, press_release_feed_url=None,
                official_x_handle=None, official_linkedin_url=data.get("li"),
                earnings_transcript_provider=data.get("tx", "none"),
                local_regulatory_filings_url=data.get("fil"),
                sub_industry_override=data.get("si"),
                confidence=float(data.get("c", 0.5)),
                authoring_notes={"reason": "delisted or no IR venue"},
            )
            continue
        agent.fill_overlay(
            row, ir_url=data.get("ir"), press_release_feed_url=data.get("press"),
            official_x_handle=data.get("x"), official_linkedin_url=data.get("li"),
            earnings_transcript_provider=data.get("tx", "seekingalpha"),
            local_regulatory_filings_url=data.get("fil"),
            sub_industry_override=data.get("si"),
            confidence=float(data.get("c", 0.7)),
        )

    print(f"[hc] overlay filled for {len(rows)} rows ({len(uncurated)} uncurated)")
    issues = agent.self_verify()
    if issues:
        for i in issues:
            print(f"  - {i}")
        return 1
    print("[hc] self-verify: 0 issues")
    out = agent.emit_enriched_sheet()
    print(f"[hc] enriched -> {out}")
    return 0


