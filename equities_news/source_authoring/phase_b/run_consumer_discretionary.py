def main() -> int:
    agent = SectorAgent("consumer_discretionary")
    agent.preflight()
    rows = agent.read_sector_sheet()
    print(f"[cd] loaded {len(rows)} rows")
    agent.author_sector_yaml(SECTOR_ENTRIES)
    print(f"[cd] authored {len(SECTOR_ENTRIES)} sector entries")
    paths = agent.author_sub_industry_yamls(SUB_INDUSTRY_ENTRIES)
    for p in paths:
        print(f"[cd] authored {p.name}")

    uncurated = []
    for row in rows:
        data = OVERLAYS.get(row.ticker)
        if data is None or not data:
            agent.fill_overlay(
                row, ir_url=None, press_release_feed_url=None, official_x_handle=None,
                official_linkedin_url=None, earnings_transcript_provider="seekingalpha",
                local_regulatory_filings_url=None, sub_industry_override=None,
                confidence=0.45, authoring_notes={"reason": "not curated"},
            )
            uncurated.append(row.ticker)
            continue
        agent.fill_overlay(
            row, ir_url=data.get("ir"), press_release_feed_url=data.get("press"),
            official_x_handle=data.get("x"), official_linkedin_url=data.get("li"),
            earnings_transcript_provider=data.get("tx", "seekingalpha"),
            local_regulatory_filings_url=data.get("fil"),
            sub_industry_override=data.get("si"),
            confidence=float(data.get("c", 0.7)),
        )

    print(f"[cd] overlay filled for {len(rows)} rows ({len(uncurated)} uncurated)")
    issues = agent.self_verify()
    if issues:
        for i in issues:
            print(f"  - {i}")
        return 1
    print("[cd] self-verify: 0 issues")
    out = agent.emit_enriched_sheet()
    print(f"[cd] enriched -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
