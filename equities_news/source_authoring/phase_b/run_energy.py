    agent = SectorAgent("energy")
    agent.preflight()
    rows = agent.read_sector_sheet()
    print(f"[energy] loaded {len(rows)} rows from bible")

    agent.author_sector_yaml(SECTOR_ENTRIES)
    print(f"[energy] authored {len(SECTOR_ENTRIES)} sector entries")

