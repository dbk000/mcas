    for p in paths:
        print(f"[energy] authored {p.name}")

    missing: list[str] = []
    for row in rows:
        data = OVERLAYS.get(row.ticker)
        if data is None or not data:
            agent.fill_overlay(
                row,
                ir_url=None,
                press_release_feed_url=None,
                official_x_handle=None,
                official_linkedin_url=None,
                earnings_transcript_provider="seekingalpha",
                local_regulatory_filings_url=None,
                sub_industry_override=None,
                confidence=0.5,
                authoring_notes={"reason": "ticker not in curated energy overlay map"},
            )
            missing.append(row.ticker)
            continue
        agent.fill_overlay(
            row,
            ir_url=data.get("ir"),
            press_release_feed_url=data.get("press"),
            official_x_handle=data.get("x"),
            official_linkedin_url=data.get("li"),
            earnings_transcript_provider=data.get("tx", "seekingalpha"),
            local_regulatory_filings_url=data.get("fil"),
            sub_industry_override=data.get("si"),
            confidence=float(data.get("c", 0.7)),
        )

    print(f"[energy] overlay filled for {len(rows)} rows ({len(missing)} uncurated)")
    if missing:
        print(f"[energy] uncurated tickers: {missing}")

    issues = agent.self_verify()
    if issues:
        print("[energy] SELF-VERIFY ISSUES:")
        for i in issues:
            print(f"  - {i}")
        return 1
    print("[energy] self-verify: 0 issues")

    out = agent.emit_enriched_sheet()
    print(f"[energy] enriched sheet -> {out}")
    return 0


