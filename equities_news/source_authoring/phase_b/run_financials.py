def _finalise_overlays() -> dict[str, dict]:
    """Merge all overlay sources into a single flat ticker->dict map.

    Priority: OVERLAYS explicit (highest) → _EXTRA → _EXTRA_INTL → _PATTERN_US fallback.
    """
    out: dict[str, dict] = {}
    # Lowest priority first — pattern-based US community banks
    for t, (slug, li_slug, si) in _PATTERN_US.items():
        li = f"https://www.linkedin.com/company/{li_slug}" if li_slug else None
        out[t] = {
            "ir": f"https://ir.{slug}.com" if "." not in slug else f"https://ir.{slug}",
            "press": f"https://ir.{slug}.com/news-releases" if "." not in slug else f"https://{slug}/news",
            "x": None, "li": li,
            "tx": "seekingalpha",
            "fil": f"https://ir.{slug}.com/sec-filings" if "." not in slug else f"https://{slug}/sec-filings",
            "si": si, "c": 0.55,
        }
    # International
    for t, rec in _EXTRA_INTL.items():
        out[t] = rec
    # US curated extras
    for t, rec in _EXTRA.items():
        out[t] = rec
    # Highest — existing OVERLAYS (full hand-curated)
    for t, rec in OVERLAYS.items():
        out[t] = rec
    return out


def main() -> int:
    agent = SectorAgent("financials")
    agent.preflight()
    rows = agent.read_sector_sheet()
    print(f"[fin] loaded {len(rows)} rows")
    agent.author_sector_yaml(SECTOR_ENTRIES)
    print(f"[fin] authored {len(SECTOR_ENTRIES)} sector entries")
    paths = agent.author_sub_industry_yamls(SUB_INDUSTRY_ENTRIES)
    for p in paths:
        print(f"[fin] authored {p.name}")

    merged = _finalise_overlays()
    print(f"[fin] overlay dict size: {len(merged)} tickers")

    uncurated = []
    filled = 0
    ir_hits = 0
    press_hits = 0
    x_hits = 0
    fil_hits = 0
    tx_hits = 0
    li_hits = 0
    for row in rows:
        # Country-aware override first (AMP/AU, PRU/UK, HBAN/CH, RF/FR, UNI/ES,
        # FBK/US, BEN/AU, HLI/AU, AUB/US)
        data = BY_COUNTRY.get((row.ticker, row.country)) or merged.get(row.ticker)
        if data is None or not data:
            agent.fill_overlay(
                row, ir_url=None, press_release_feed_url=None, official_x_handle=None,
                official_linkedin_url=None, earnings_transcript_provider="seekingalpha",
                local_regulatory_filings_url=None, sub_industry_override=None,
                confidence=0.45, authoring_notes={"reason": "not curated"},
            )
            uncurated.append(row.ticker)
            continue
        agent.fill_overlay(
            row, ir_url=data.get("ir"), press_release_feed_url=data.get("press"),
            official_x_handle=data.get("x"), official_linkedin_url=data.get("li"),
            earnings_transcript_provider=data.get("tx", "seekingalpha"),
            local_regulatory_filings_url=data.get("fil"),
            sub_industry_override=data.get("si"),
            confidence=float(data.get("c", 0.7)),
        )
        filled += 1
        if data.get("ir"): ir_hits += 1
        if data.get("press"): press_hits += 1
        if data.get("x"): x_hits += 1
        if data.get("fil"): fil_hits += 1
        if data.get("li"): li_hits += 1
        if data.get("tx") and data.get("tx") != "none": tx_hits += 1

    n = len(rows)
    print(f"[fin] overlay filled for {n} rows ({len(uncurated)} uncurated)")
    print(f"[fin] fill rates: IR={ir_hits}/{n}={100*ir_hits/n:.1f}% "
          f"Press={press_hits}/{n}={100*press_hits/n:.1f}% "
          f"X={x_hits}/{n}={100*x_hits/n:.1f}% "
          f"LinkedIn={li_hits}/{n}={100*li_hits/n:.1f}% "
          f"Transcript={tx_hits}/{n}={100*tx_hits/n:.1f}% "
          f"Fil={fil_hits}/{n}={100*fil_hits/n:.1f}%")
    issues = agent.self_verify()
    if issues:
        for i in issues:
            print(f"  - {i}")
        return 1
    print("[fin] self-verify: 0 issues")
    out = agent.emit_enriched_sheet()
    print(f"[fin] enriched -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
